import XCTest
@testable import Shelf

final class MonitorTests: XCTestCase {
    func testDigestIsStableAndKindSpecific() {
        let data = Data("same".utf8)
        XCTAssertEqual(Monitor.digest("text", data), Monitor.digest("text", data))
        XCTAssertNotEqual(Monitor.digest("text", data), Monitor.digest("file", data))
        XCTAssertNotEqual(Monitor.digest("text", data), Monitor.digest("text", Data("other".utf8)))
        XCTAssertEqual(Monitor.digest("text", data).count, 64)   // hex SHA-256
    }

    func testSkipsConcealedAndTransientCopies() {
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

        XCTAssertEqual(Monitor.skipReason([.string, concealed]), .concealed)
        XCTAssertEqual(Monitor.skipReason([.string, transient]), .transient)
        XCTAssertEqual(Monitor.skipReason([.string, autoGenerated]), .transient)
        // A password that's also marked transient still gets the password hint.
        XCTAssertEqual(Monitor.skipReason([.string, concealed, transient]), .concealed)
        XCTAssertNil(Monitor.skipReason([.string, .rtf]))
        XCTAssertNil(Monitor.skipReason([]))
    }

    func testCopiesFromPasswordManagersAreConcealedEvenWhenUnmarked() {
        // Plain text with no concealed marker, copied while a password manager is frontmost.
        XCTAssertEqual(Monitor.skipReason([.string], from: "com.apple.Passwords"), .concealed)
        XCTAssertEqual(Monitor.skipReason([.string], from: "com.apple.keychainaccess"), .concealed)
        XCTAssertEqual(Monitor.skipReason([.string], from: "com.1password.1password"), .concealed)
        XCTAssertNil(Monitor.skipReason([.string], from: "com.apple.Notes"))
        XCTAssertNil(Monitor.skipReason([.string], from: nil))
    }

    func testIgnoredAppsAreSkipped() {
        let ignored: Set<String> = ["com.tinyspeck.slackmacgap"]
        XCTAssertEqual(Monitor.skipReason([.string], from: "com.tinyspeck.slackmacgap", ignoring: ignored), .ignored)
        XCTAssertNil(Monitor.skipReason([.string], from: "com.apple.Notes", ignoring: ignored))
        XCTAssertNil(Monitor.skipReason([.string], from: nil, ignoring: ignored))
        // A password manager on the ignore list still gets the password card.
        XCTAssertEqual(Monitor.skipReason([.string], from: "com.apple.Passwords", ignoring: ["com.apple.Passwords"]),
                       .concealed)
    }

    func testIsLink() {
        XCTAssertTrue(Monitor.isLink("https://example.com"))
        XCTAssertTrue(Monitor.isLink("  http://example.com/path?q=1\n"))
        XCTAssertFalse(Monitor.isLink("example.com"))
        XCTAssertFalse(Monitor.isLink("ftp://example.com"))
        XCTAssertFalse(Monitor.isLink("see https://example.com"))
        XCTAssertFalse(Monitor.isLink("https://"))
        XCTAssertFalse(Monitor.isLink(""))
    }
}
